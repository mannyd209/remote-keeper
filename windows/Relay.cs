// The connection to the Remote Keeper relay, and the end-to-end encryption that keeps the relay from
// reading or faking anything. Must match the Mac app (mac/Relay.swift) and the web app
// (relay/public/crypto.js): HKDF-SHA256 with salt "remote-keeper v1" derives the channel id and one
// AES-256-GCM key per direction; sealed messages are base64url(nonce(12) || ciphertext || tag(16)).

using System.Net.WebSockets;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json.Nodes;

namespace RemoteKeeper;

static class Relay
{
    // Official releases have the relay and its app key built in (BuildConfig.cs, generated by
    // build.sh from a private file). Builds from the public source have neither: run your own relay
    // and set REMOTE_KEEPER_HOST and REMOTE_KEEPER_APP_KEY.
    public static readonly string Host = Environment.GetEnvironmentVariable("REMOTE_KEEPER_HOST") ?? BuildConfig.RelayHost;
    public static readonly string AppKey = Environment.GetEnvironmentVariable("REMOTE_KEEPER_APP_KEY")
        ?? Encoding.UTF8.GetString(BuildConfig.AppKeyMasked.Zip(BuildConfig.AppKeyMask, (a, b) => (byte)(a ^ b)).ToArray());
    public static bool Configured => Host.Length > 0 && AppKey.Length > 0;
    public static bool IsLocal => Host.StartsWith("localhost") || Host.StartsWith("127.0.0.1");

    /// How far this PC's clock is off from the relay's (ms to add). The relay and your phone only
    /// accept messages stamped within a few minutes, and PCs (virtual machines especially) can drift.
    public static long ClockOffsetMs;
    static DateTime offsetCheckedAt = DateTime.MinValue;

    /// The relay's time, from its Date header (checked at most every 10 minutes).
    public static async Task SyncClockAsync()
    {
        if (DateTime.UtcNow - offsetCheckedAt < TimeSpan.FromMinutes(10) || !Configured) return;
        offsetCheckedAt = DateTime.UtcNow;
        try
        {
            using var http = new HttpClient { Timeout = TimeSpan.FromSeconds(10) };
            var sent = DateTimeOffset.UtcNow;
            using var response = await http.SendAsync(new HttpRequestMessage(HttpMethod.Head, $"{(IsLocal ? "http" : "https")}://{Host}/"));
            var received = DateTimeOffset.UtcNow;
            if (response.Headers.Date is DateTimeOffset server)
            {
                var local = sent + (received - sent) / 2;
                var offset = (long)(server - local).TotalMilliseconds;
                // The header has whole seconds: only correct a real difference.
                ClockOffsetMs = Math.Abs(offset) > 2000 ? offset : 0;
                if (ClockOffsetMs != 0) Log.Write($"This PC's clock is {-ClockOffsetMs / 1000.0:0}s off from the relay's; correcting for it");
            }
        }
        catch (Exception e) { Log.Write("Clock check: " + e.Message); }
    }

    public static long NowMs => DateTimeOffset.UtcNow.ToUnixTimeMilliseconds() + ClockOffsetMs;

    /// Proves to the relay that this is Remote Keeper (the relay's macSignatureValid).
    public static string Signature(string channel)
    {
        var ms = NowMs.ToString();
        var mac = HMACSHA256.HashData(Encoding.UTF8.GetBytes(AppKey), Encoding.UTF8.GetBytes($"mac.{channel}.{ms}"));
        return $"{ms}.{Base64Url.Encode(mac)}";
    }
}

sealed class ChannelKeys
{
    public readonly string Channel;
    readonly byte[] toMac, toPhone;
    const double MaxAgeSeconds = 5 * 60;

    public ChannelKeys(byte[] secret)
    {
        byte[] Derive(string info) => HKDF.DeriveKey(HashAlgorithmName.SHA256, secret, 32, Encoding.UTF8.GetBytes("remote-keeper v1"), Encoding.UTF8.GetBytes(info));
        Channel = Convert.ToHexString(Derive("channel")).ToLowerInvariant();
        toMac = Derive("to-mac");
        toPhone = Derive("to-phone");
    }

    public string? Seal(JsonObject message)
    {
        message["ts"] = Relay.NowMs;
        message["n"] = Base64Url.Encode(RandomNumberGenerator.GetBytes(9));
        var plain = Encoding.UTF8.GetBytes(message.ToJsonString());
        var nonce = RandomNumberGenerator.GetBytes(12);
        var cipher = new byte[plain.Length];
        var tag = new byte[16];
        using var aes = new AesGcm(toPhone, 16);
        aes.Encrypt(nonce, plain, cipher, tag);
        return Base64Url.Encode(nonce.Concat(cipher).Concat(tag).ToArray());
    }

    /// The message, or null if it wasn't sealed by a linked phone or is stale.
    public JsonObject? Open(string text)
    {
        try
        {
            var data = Base64Url.Decode(text);
            if (data == null || data.Length < 28) return null;
            var nonce = data[..12];
            var tag = data[^16..];
            var cipher = data[12..^16];
            var plain = new byte[cipher.Length];
            using var aes = new AesGcm(toMac, 16);
            aes.Decrypt(nonce, cipher, tag, plain);
            if (JsonNode.Parse(plain) is not JsonObject message) return null;
            var ts = Json.Double(message["ts"]);
            if (ts == null || Math.Abs(Relay.NowMs / 1000.0 - ts.Value / 1000) >= MaxAgeSeconds) return null;
            return message;
        }
        catch { return null; }
    }
}

/// One WebSocket to the relay, kept open: reconnects after errors, sleep or network changes.
sealed class RelayConnection
{
    readonly ChannelKeys keys;
    readonly Action<JsonObject> onMessage;
    readonly Action<bool> onState;
    readonly SemaphoreSlim sendLock = new(1, 1);
    readonly Dictionary<string, DateTime> seen = new();   // nonces of recent messages, so a replay is ignored
    ClientWebSocket? socket;
    DateTime lastHeard = DateTime.UtcNow;
    volatile bool stopped;
    Timer? heartbeat;
    public volatile bool Connected;

    public RelayConnection(ChannelKeys keys, Action<JsonObject> onMessage, Action<bool> onState)
    {
        this.keys = keys;
        this.onMessage = onMessage;
        this.onState = onState;
    }

    public void Start()
    {
        _ = Task.Run(RunAsync);
        // Heartbeat: Cloudflare answers {"t":"ping"} with {"t":"pong"} without waking the relay.
        heartbeat = new Timer(_ =>
        {
            var s = socket;
            if (stopped || s == null || s.State != WebSocketState.Open) return;
            if (DateTime.UtcNow - lastHeard > TimeSpan.FromSeconds(70))
            {
                Log.Write("Relay went quiet; reconnecting");
                s.Abort();
                return;
            }
            _ = SendRawAsync("{\"t\":\"ping\"}");
        }, null, TimeSpan.FromSeconds(25), TimeSpan.FromSeconds(25));
    }

    public void Stop()
    {
        stopped = true;
        heartbeat?.Dispose();
        try { socket?.Abort(); } catch { }
    }

    async Task RunAsync()
    {
        var retry = 0;
        while (!stopped && Relay.Configured)
        {
            await Relay.SyncClockAsync();
            var ws = new ClientWebSocket();
            ws.Options.SetRequestHeader("User-Agent", $"RemoteKeeper/{App.Version} (Windows)");
            ws.Options.SetRequestHeader("X-Keeper-Auth", Relay.Signature(keys.Channel));
            ws.Options.KeepAliveInterval = TimeSpan.Zero;
            var uri = new Uri($"{(Relay.IsLocal ? "ws" : "wss")}://{Relay.Host}/v1/ws?c={keys.Channel}&role=mac");
            try
            {
                using var cts = new CancellationTokenSource(TimeSpan.FromSeconds(20));
                await ws.ConnectAsync(uri, cts.Token);
                socket = ws;
                lastHeard = DateTime.UtcNow;
                retry = 0;
                Connected = true;
                onState(true);
                await ReceiveAsync(ws);
            }
            catch (Exception e) when (!stopped)
            {
                if (retry == 0) Log.Write("Relay connection: " + e.Message);
            }
            finally
            {
                if (ReferenceEquals(socket, ws)) socket = null;
                if (Connected) { Connected = false; onState(false); }
                ws.Dispose();
            }
            if (stopped) break;
            var delay = Math.Min(30, Math.Pow(2, retry));
            retry++;
            await Task.Delay(TimeSpan.FromSeconds(delay));
        }
    }

    async Task ReceiveAsync(ClientWebSocket ws)
    {
        var buffer = new byte[64 * 1024];
        var message = new MemoryStream();
        while (ws.State == WebSocketState.Open && !stopped)
        {
            var result = await ws.ReceiveAsync(buffer, CancellationToken.None);
            if (result.MessageType == WebSocketMessageType.Close) break;
            message.Write(buffer, 0, result.Count);
            if (!result.EndOfMessage) continue;
            lastHeard = DateTime.UtcNow;
            var text = Encoding.UTF8.GetString(message.ToArray());
            message.SetLength(0);
            if (result.MessageType == WebSocketMessageType.Text) Handle(text);
        }
    }

    void Handle(string text)
    {
        try
        {
            if (JsonNode.Parse(text) is not JsonObject frame || frame["m"] is not JsonValue v || !v.TryGetValue<string>(out var sealedText)) return;
            var message = keys.Open(sealedText);
            if (message == null) return;
            var nonce = Json.Str(message["n"]);
            var now = DateTime.UtcNow;
            lock (seen)
            {
                foreach (var old in seen.Where(p => (now - p.Value).TotalSeconds >= 600).Select(p => p.Key).ToList()) seen.Remove(old);
                if (seen.ContainsKey(nonce)) return;
                seen[nonce] = now;
            }
            onMessage(message);
        }
        catch (Exception e) { Log.Write("Relay message: " + e.Message); }
    }

    /// Sends a sealed message to every phone that is connected right now.
    public void Send(JsonObject message) { var s = keys.Seal(message); if (s != null) Frame(new JsonObject { ["m"] = s }); }

    /// Sends a sealed alert as a push notification to every phone that turned alerts on.
    public void Push(JsonObject message) { var s = keys.Seal(message); if (s != null) Frame(new JsonObject { ["push"] = s }); }

    /// Hands the relay a sealed alert to send to your phones if this PC goes quiet for 5 minutes
    /// without withdrawing it (shut down, crashed, lost power or network).
    public void SetWill(JsonObject message) { var s = keys.Seal(message); if (s != null) Frame(new JsonObject { ["will"] = s }); }

    /// Withdraws it before sleeping or quitting. Waits up to a second, so it goes out before exit.
    public void WithdrawWill()
    {
        try { SendRawAsync("{\"will\":\"off\"}").Wait(TimeSpan.FromSeconds(1)); } catch { }
    }

    void Frame(JsonObject o) => _ = SendRawAsync(o.ToJsonString());

    async Task SendRawAsync(string text)
    {
        var ws = socket;
        if (ws == null || ws.State != WebSocketState.Open) return;
        await sendLock.WaitAsync();
        try { await ws.SendAsync(Encoding.UTF8.GetBytes(text), WebSocketMessageType.Text, true, CancellationToken.None); }
        catch { }
        finally { sendLock.Release(); }
    }
}
