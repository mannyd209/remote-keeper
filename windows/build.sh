#!/bin/bash
# Builds Remote Keeper for Windows: one self-contained RemoteKeeper.exe per chip, in build/:
#   build/Remote-Keeper-Windows-arm64.exe   build/Remote-Keeper-Windows-x64.exe
# Needs the .NET 8 SDK (dotnet on PATH, or ~/.dotnet). Works on macOS (cross-builds) and Windows.
#
# Official builds have the relay built in, from a private file:
#   ~/.config/remotekeeper/build.env  with  RK_RELAY_HOST=…  and  RK_APP_KEY_FILE=…
# Without it you get a build with no relay (set REMOTE_KEEPER_HOST / REMOTE_KEEPER_APP_KEY to use
# your own).
set -euo pipefail
cd "$(dirname "$0")"
export DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1
DOTNET=$(command -v dotnet || echo "$HOME/.dotnet/dotnet")

[ -f "$HOME/.config/remotekeeper/build.env" ] && . "$HOME/.config/remotekeeper/build.env"
RK_APP_KEY=""
[ -n "${RK_APP_KEY_FILE:-}" ] && RK_APP_KEY=$(cat "${RK_APP_KEY_FILE/#\~/$HOME}")
RK_RELAY_HOST="${RK_RELAY_HOST:-}" RK_APP_KEY="$RK_APP_KEY" python3 - BuildConfig.cs <<'PY'
import os, sys, secrets
key = os.environ["RK_APP_KEY"].encode()
mask = secrets.token_bytes(len(key))
masked = bytes(a ^ b for a, b in zip(key, mask))
arr = lambda b: ", ".join(str(x) for x in b)
with open(sys.argv[1], "w") as f:
    f.write("// Generated by build.sh. Do not commit.\nnamespace RemoteKeeper;\nstatic class BuildConfig\n{\n")
    f.write(f'    public const string RelayHost = "{os.environ["RK_RELAY_HOST"]}";\n')
    f.write(f"    public static readonly byte[] AppKeyMasked = {{ {arr(masked)} }};\n")
    f.write(f"    public static readonly byte[] AppKeyMask = {{ {arr(mask)} }};\n}}\n")
PY
[ -n "${RK_RELAY_HOST:-}" ] && echo "Relay: $RK_RELAY_HOST (app key built in)" || echo "No relay built in (source build)"

mkdir -p build
for arch in arm64 x64; do
  rm -rf obj bin
  "$DOTNET" publish -c Release -r "win-$arch" -o "build/$arch" -nologo -v quiet 2>&1 | grep -E " error |warning CS" || true
  cp "build/$arch/RemoteKeeper.exe" "build/Remote-Keeper-Windows-$arch.exe"
  rm -rf "build/$arch"
done
rm -f BuildConfig.cs
rm -rf obj bin
ls -la build/*.exe
shasum -a 256 build/*.exe
