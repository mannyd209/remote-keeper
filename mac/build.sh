#!/bin/bash
# Builds and signs (Developer ID, hardened runtime) Remote Keeper.app, universal.
# Builds outside the project folder: iCloud-synced folders (like Desktop) add Finder metadata to
# bundles, which codesign refuses.
set -euo pipefail
cd "$(dirname "$0")"
VERSION=$(sed -n 's/^let keeperVersion = "\(.*\)"/\1/p' main.swift)
IDENTITY=$(security find-identity -v -p codesigning | awk '/Developer ID Application/{print $2; exit}')
BUILD="${BUILD_DIR:-$HOME/Library/Developer/RemoteKeeper}"
APP="$BUILD/Remote Keeper.app"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# The relay and its app key come from a private file, never from this repo:
#   ~/.config/remotekeeper/build.env  with  RK_RELAY_HOST=…  and  RK_APP_KEY_FILE=…
# Without it you get a build with no relay (set REMOTE_KEEPER_HOST / REMOTE_KEEPER_APP_KEY to use
# your own).
[ -f "$HOME/.config/remotekeeper/build.env" ] && . "$HOME/.config/remotekeeper/build.env"
RK_APP_KEY=""
[ -n "${RK_APP_KEY_FILE:-}" ] && RK_APP_KEY=$(cat "${RK_APP_KEY_FILE/#\~/$HOME}")
RK_RELAY_HOST="${RK_RELAY_HOST:-}" RK_APP_KEY="$RK_APP_KEY" python3 - "$BUILD/BuildConfig.swift" <<'PY'
import os, secrets, sys
key = os.environ["RK_APP_KEY"].encode()
mask = secrets.token_bytes(len(key))
masked = bytes(a ^ b for a, b in zip(key, mask))
with open(sys.argv[1], "w") as f:
    f.write("// Generated by build.sh. Official releases fill these in; builds from source leave them empty.\n")
    f.write(f'let builtInRelayHost = "{os.environ["RK_RELAY_HOST"]}"\n')
    f.write(f"let builtInAppKeyMasked: [UInt8] = {list(masked)}\n")
    f.write(f"let builtInAppKeyMask: [UInt8] = {list(mask)}\n")
PY
[ -n "${RK_RELAY_HOST:-}" ] && echo "Relay: $RK_RELAY_HOST (app key built in)" || echo "No relay built in (source build)"

for arch in arm64 x86_64; do
  swiftc -O -swift-version 5 -target "$arch-apple-macos13" Sessions.swift Relay.swift Keeper.swift Checks.swift Updater.swift Lifeline.swift AppUI.swift main.swift "$BUILD/BuildConfig.swift" -o "$BUILD/RemoteKeeper-$arch"
done
lipo -create "$BUILD/RemoteKeeper-arm64" "$BUILD/RemoteKeeper-x86_64" -output "$APP/Contents/MacOS/RemoteKeeper"
rm "$BUILD/RemoteKeeper-arm64" "$BUILD/RemoteKeeper-x86_64" "$BUILD/BuildConfig.swift"
cp Resources/AppIcon.icns "$APP/Contents/Resources/"
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleIdentifier</key><string>com.mannydlabs.remotekeeper</string>
  <key>CFBundleName</key><string>Remote Keeper</string>
  <key>CFBundleDisplayName</key><string>Remote Keeper</string>
  <key>CFBundleExecutable</key><string>RemoteKeeper</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundleVersion</key><string>$VERSION</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <key>LSUIElement</key><true/>
  <key>LSApplicationCategoryType</key><string>public.app-category.developer-tools</string>
  <key>NSHumanReadableCopyright</key><string>© 2026 MannyD Labs. Not affiliated with Anthropic.</string>
</dict></plist>
PLIST
# The login agent launchd keeps alive (see Lifeline.swift): restarts it if it's killed or crashes,
# but not after Quit (a clean exit).
mkdir -p "$APP/Contents/Library/LaunchAgents"
cat > "$APP/Contents/Library/LaunchAgents/com.mannydlabs.remotekeeper.agent.plist" <<AGENT
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>com.mannydlabs.remotekeeper.agent</string>
  <key>BundleProgram</key><string>Contents/MacOS/RemoteKeeper</string>
  <key>AssociatedBundleIdentifiers</key><array><string>com.mannydlabs.remotekeeper</string></array>
  <key>EnvironmentVariables</key><dict><key>REMOTE_KEEPER_AGENT</key><string>1</string></dict>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>
  <key>ThrottleInterval</key><integer>10</integer>
  <key>ProcessType</key><string>Interactive</string>
  <key>LimitLoadToSessionType</key><string>Aqua</string>
  <key>AbandonProcessGroup</key><true/>
</dict></plist>
AGENT
codesign --force --options runtime --timestamp --sign "$IDENTITY" "$APP"
codesign --verify --strict "$APP"
echo "Built: $APP ($VERSION)"
